def search_knowledge(query: str) -> List[Dict[str, Any]]:
    """사용자 질의와 가장 관련된 노무 지식 베이스 항목을 검색합니다."""
    matched = []
    tokens = [t.strip().lower() for t in query.split() if len(t.strip()) > 1]
    
    for item in QA_KNOWLEDGE_BASE:
        score = 0
        for kw in item["keywords"]:
            if kw in query:
                score += 3
            for t in tokens:
                if kw in t or t in kw:
                    score += 1
        if score > 0:
            matched.append((score, item))
            
    matched.sort(key=lambda x: x[0], reverse=True)
    return [item for _, item in matched[:2]]
